print('3.8放眼世界')
citys=['beijing', 'new york city', 'tokyo', 'paris', 'mexico city']
print(citys)

print(sorted(citys))

print(citys)

print(sorted(citys,reverse=True))

print(citys)

citys.reverse()
print(citys)

citys.reverse()
print(citys)

print(sorted(citys))

print(sorted(citys,reverse=True))

